PRON = [
 ("Stress is free and mobile","It can fall on any syllable and moves within a word's forms: "
  "го́род → города́. Learning a word without its stress means learning it wrong."),
 ("Unstressed О → [а]","молоко́ is said [малако́], хорошо́ [харашо́]. Only the STRESSED о "
  "is a true [o]."),
 ("Unstressed О/А far from the stress → [ə]","A weak schwa, like the a in 'about': "
  "мо́локо [мо́лəкə], ко́мната [ко́мнətə]."),
 ("Unstressed Е/Я → [и]","сестра́ [систра́], язы́к [йизы́к], пятно́ [питно́]."),
 ("Final voiced consonants devoice","хлеб [хлеп], го́род [го́рат], муж [муш], нож [нош]. "
  "Spelling keeps the voiced letter; pronunciation does not."),
 ("Devoicing before a voiceless consonant","во́дка [во́тка], ло́жка [ло́шка], "
  "автобус [афто́бус]."),
 ("Voicing before a voiced consonant","сдать [здать], вокза́л [вагза́л], футбо́л [фудбо́л]."),
 ("-ОГО / -ЕГО → [-ова / -ева]","The Г is pronounced [в]: его́ [ево́], большо́го [бальшо́ва], "
  "сего́дня [сево́дня]. Applies to all adjective/pronoun genitive endings."),
 ("ЧТО → [што]","Also коне́чно [кане́шна] and ску́чно [ску́шна]. A short closed list — "
  "elsewhere чт and чн are said as written."),
 ("-ТСЯ / -ТЬСЯ → [ца]","учи́ться [учи́ца], нра́вится [нра́вица]. One sound, not three."),
 ("Ж, Ш, Ц are ALWAYS hard","Even written with и or е: жи [жы], ши [шы], "
  "цирк [цырк], жена́ [жына́]."),
 ("Ч, Щ, Й are ALWAYS soft","No matter what follows: часы́, щи, чай."),
 ("Ь softens the consonant before it","брат (hard) vs брать (soft). This is a real change "
  "of meaning, not decoration: мат / мать, был / быль."),
 ("Ъ is a separator","It blocks softening and inserts a [й]: съесть [сйэсть], "
  "объясни́ть [абйисни́ть]."),
 ("СЧ / ЗЧ → [щ]","сча́стье [ща́стье], счёт [щёт], мужчи́на [мущи́на]."),
 ("Silent consonants: СТН, ЗДН, ЛНЦ","изве́стный [изве́сный], по́здно [по́зна], "
  "со́лнце [со́нце], здра́вствуйте [здра́ствуйте]."),
 ("Е after Ж, Ш, Ц when unstressed → [ы]","жена́ [жына́], шести́ [шысти́], цена́ [цына́]."),
 ("Ё is always stressed","If you see ё, that is the stress — and it is often printed as е, "
  "which is why stress marks matter."),
 ("Р is rolled, Л is dark","Russian л is 'thick' (like the l in 'full'), not the light "
  "English l in 'leaf'."),
 ("Doubled consonants are usually shortened","ру́сский [ру́ский], гру́ппа [гру́па] — "
  "though a careful speaker may hold them."),
 ("Vowel reduction ladder","Stressed = full. One syllable before the stress = half-reduced. "
  "Everywhere else = schwa. This rhythm is most of a Russian accent."),
 ("Г in some words → [х]","In бог [бох] and in the exclamation ага́. Regional, but common."),
]

