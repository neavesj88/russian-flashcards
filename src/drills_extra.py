def gen_adj(add):
    for lemma, gloss, forms, note in ADJ:
        for label, idx in SLOTS:
            add("adj", f"{lemma} → {label}", forms[idx],
                [f for i, f in enumerate(forms) if i != idx] + [lemma],
                f"{lemma} ({gloss}) — {note}. {label.capitalize()}: {forms[idx]}.",
                gloss)

